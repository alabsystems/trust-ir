fn assert_v32_debug_metadata(module: &Module) {
    use trust_ir::Producer;
    use trust_ir::value::ValueId;

    assert_eq!(module.name, "v32_debug_metadata");
    assert_eq!(module.functions.len(), 2);
    let function = module
        .functions
        .iter()
        .find(|function| function.name == "named_call")
        .expect("pinned v32 caller");
    assert_eq!(
        function.producer,
        Some(Producer::Other("v32 fixture producer".to_string()))
    );
    assert_eq!(
        function.value_names.as_deref(),
        Some(
            &[
                (ValueId::new(7), "input".to_string()),
                (ValueId::new(9), "result, renamed\n".to_string()),
            ][..]
        )
    );
    assert_eq!(
        function.scopes, None,
        "v32 function defaults the v33 scope tree"
    );
    let call = &function.blocks[0].body[0];
    assert_eq!(call.scope, None, "v32 node defaults the v33 scope index");
    let context = call
        .proof_context
        .as_ref()
        .expect("the field immediately preceding v33 scope remains aligned");
    assert!(context.assumes.is_empty());
    assert!(context.establishes.is_empty());

    let errors = trust_ir_build::validate_module(module);
    assert!(
        errors.is_empty(),
        "the immutable v32 compatibility artifact must remain a valid module: {errors:#?}"
    );
}

#[test]
fn v32_binary_debug_metadata_defaults_v33_scopes_without_desynchronizing() {
    let bytes = read_compat("v32_debug_metadata.tmbc");
    assert_eq!(u32::from_le_bytes(bytes[8..12].try_into().unwrap()), 32);
    let module = trust_ir::binary::deserialize_module(&bytes)
        .expect("pinned v32 debug-metadata binary must keep decoding");
    assert_v32_debug_metadata(&module);

    let current = trust_ir::binary::serialize_module(&module);
    assert_eq!(
        u32::from_le_bytes(current[8..12].try_into().unwrap()),
        trust_ir::binary::VERSION,
        "re-encoded artifact must carry the current format version"
    );
    let round_tripped = trust_ir::binary::deserialize_module(&current)
        .expect("v32 semantics re-encoded at the current VERSION must decode");
    assert_eq!(round_tripped, module);
}

#[test]
fn v32_msgpack_debug_metadata_defaults_v33_scopes_without_shifting_fields() {
    let module: Module = rmp_serde::from_slice(&read_compat("v32_debug_metadata.msgpack"))
        .expect("pinned v32 positional MessagePack must keep decoding");
    assert_v32_debug_metadata(&module);
}
