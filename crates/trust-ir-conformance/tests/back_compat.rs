// Wire-compatibility gates across the v24 READ-FLOOR MOVE (RFC TRUST_IR_V2
// Phase 2: MIN_READ_VERSION 2 -> 23, the program's one deliberate break).
//
// The blobs under `tests/fixtures/compat/` are PINNED compatibility artifacts.
// The v22 pair was captured at trust-ir v22 (commit 9d08ce4's tree); the v30
// `ty_composite` pair was captured immediately before the v31 enum-record
// extension. The v32 debug-metadata pair was emitted by commit 86685a9,
// immediately before v33 appended lexical scopes. Unlike the live goldens
// in `tests/fixtures/`, they are NEVER regenerated by
// `TRUST_IR_UPDATE_FIXTURES=1`. Their role FLIPPED at v24:
//
// * binary (`.tmbc`, header version 22): the reader now REJECTS the blob
//   with `UnsupportedVersion` at the header check — these fixtures PIN the
//   deliberate Phase-2 break (a v22 blob silently decoding again would mean
//   the floor regressed);
// * MessagePack (`.msgpack`, positional): serde carries NO version gate, so
//   the trailing-field discipline still applies — a pre-v23 function array
//   stops at `attrs` or `summary`, and `summary`/`producer` must keep
//   decoding via `serde(default)` from the shorter array. This half is
//   UNCHANGED by the floor move.
//
// If the msgpack test fails, the serde trailing-field discipline broke —
// a format bug, not a fixture to update. If the tmbc test fails, either the
// floor regressed or the rejection error changed shape.

use std::path::{Path, PathBuf};

use trust_ir::Module;

#[allow(dead_code)]
mod generate;

fn compat_dir() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("tests")
        .join("fixtures")
        .join("compat")
}

fn read_compat(name: &str) -> Vec<u8> {
    let path = compat_dir().join(name);
    std::fs::read(&path).unwrap_or_else(|e| {
        panic!(
            "missing pinned compat blob {} ({e}); these are never regenerated",
            path.display()
        )
    })
}

#[test]
fn v22_binary_blob_rejected_below_read_floor() {
    // v24 floor move: BOTH pinned v22 blobs must be rejected wholesale at
    // the header version check — no decoder arm may run on them. This is
    // the pinned spelling of the Phase-2 break.
    for name in ["v22_composition.tmbc", "v22_frontend_emission_subset.tmbc"] {
        let err = trust_ir::binary::deserialize_module(&read_compat(name))
            .expect_err("a v22 blob must be rejected once MIN_READ_VERSION is 23");
        assert!(
            matches!(err, trust_ir::binary::BinaryError::UnsupportedVersion),
            "{name}: expected UnsupportedVersion, got {err:?}"
        );
    }
}

#[test]
fn v22_msgpack_blob_decodes_with_producer_none() {
    // Positional MessagePack: the composition functions carry `summary`
    // (10-element array, the pre-v23 maximum), the frontend functions do not
    // (9-element array). Both must decode with `producer` defaulting to
    // `None` — this is the serde(default) half of the trailing-field
    // discipline.
    let module: Module = rmp_serde::from_slice(&read_compat("v22_composition.msgpack"))
        .expect("pinned v22 composition .msgpack must keep decoding");
    let names: Vec<&str> = module.functions.iter().map(|f| f.name.as_str()).collect();
    assert_eq!(names, vec!["reciprocal", "passthrough"]);
    for f in &module.functions {
        assert_eq!(f.producer, None);
        assert!(f.summary.is_some(), "summary present on the v22 side");
    }

    let module: Module =
        rmp_serde::from_slice(&read_compat("v22_frontend_emission_subset.msgpack"))
            .expect("pinned v22 frontend_emission_subset .msgpack must keep decoding");
    let names: Vec<&str> = module.functions.iter().map(|f| f.name.as_str()).collect();
    assert_eq!(names, vec!["checked_add", "sum3"]);
    for f in &module.functions {
        assert_eq!(f.producer, None);
        assert_eq!(f.summary, None, "no summary on the v22 side");
    }
}

#[test]
fn v30_enum_binary_blob_defaults_v31_fields_and_reaches_trailing_sections() {
    let bytes = read_compat("v30_ty_composite.tmbc");
    assert_eq!(u32::from_le_bytes(bytes[8..12].try_into().unwrap()), 30);
    let module = trust_ir::binary::deserialize_module(&bytes)
        .expect("pinned v30 enum-bearing binary must keep decoding");
    assert_eq!(module.enums.len(), 2);
    for enm in &module.enums {
        assert_eq!(enm.layout, None);
        assert!(
            enm.variants
                .iter()
                .all(|variant| variant.field_names.is_empty())
        );
    }
    // These are the v30 trailing typed-value sections. Reaching their decoded
    // defaults proves the v31 enum-record gates did not desynchronize the
    // remainder of the module.
    assert!(module.universes.is_empty());
    assert!(module.predicates.is_empty());

    assert_eq!(
        module,
        generate::build_ty_composite(),
        "v30 decoding must preserve the complete typed-model module semantics"
    );
    let current = trust_ir::binary::serialize_module(&module);
    let round_tripped = trust_ir::binary::deserialize_module(&current)
        .expect("v30 semantics re-encoded in the current wire version must decode");
    assert_eq!(round_tripped, module);
}

